const variantColorResolver: VariantColorsResolver = (input) => {
  if (input.variant !== 'soft' && input.variant !== 'tint') return defaultVariantColorsResolver(input);
  const parsed = parseThemeColor({ color: input.color || input.theme.primaryColor, theme: input.theme });
  const base = parsed.isThemeColor ? `var(${parsed.variable})` : parsed.value;
  if (input.variant === 'tint')
    return {
      background: tint(base, 18),
      hover: tint(base, 24),
      color: parsed.isThemeColor ? lightDark(c(parsed.color as BwfColor, 8), c(parsed.color as BwfColor, 2)) : base,
      border: 'none',
    };
  return {
    background: tint(base, 8),
    hover: tint(base, 20),
    color: lightDark(c('red', 8), mix(c('red', 2), c('dark', 2), 25)),
    hoverColor: lightDark(c('red', 9), 'var(--mantine-color-white)'),
    border: `1px solid ${mix(base, lightDark(c('gray', 4), c('dark', 5)), 30)}`,
  };
};

